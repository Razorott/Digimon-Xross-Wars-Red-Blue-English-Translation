def fit(value: str) -> str:
    return "\n".join("\n".join(textwrap.wrap(line, width=15,
        break_long_words=True, break_on_hyphens=False)) if line else ""
        for line in value.split("\n"))


def main() -> None:
    records = collect_messages(Rom(rom_paths()["blue"]))
    prior = translate_records(records)
    blocks, review = [], []
    for (entry, index), raw_english in FARM.items():
        key = f"MSG/MESPAK05.PAK:{entry:03d}:{index:05d}"
        if key in prior:
            raise ValueError(f"Already translated: {key}")
        row = records.get(key)
        if not row or not row["source"].strip():
            raise ValueError(f"Missing DigiFarm source: {key}")
        english = fit(raw_english)
        blocks.append({"archive": row["archive"], "entry": entry,
            "start": index, "category": "DigiFarm reports", "english": [english],
            "sources": [], "review_note": "Original Japanese DigiFarm activity report; comic voice and wordplay adapted into concise English and wrapped to the story line width."})
        review.append({"id": key, "japanese": row["source"], "english": english,
            "category": "DigiFarm reports", "evidence_url": LOCAL,
            "review_note": "Reward stats and item names follow the existing game glossary."})
    if len(blocks) != 257:
        raise ValueError(f"Expected 257 farm messages, authored {len(blocks)}")
    path = ROOT / "translations/batch42.json"
    if path.exists():
        raise FileExistsError(path)
    path.write_text(json.dumps({"description": "Translate the remaining comic DigiFarm reports, facility events, training, and rewards.", "blocks": blocks}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "translations/review_batch42.json").write_text(json.dumps({"batch": 42, "translated_slots": len(blocks), "groups": review}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ["# Batch 42 review", "", "Batch 42 completes the currently identified DigiFarm report backlog with 257 translated slots. The distinct Kansai-flavored and rock-star voices are adapted in English, while the original Japanese remains alongside each translation for review. Lines are wrapped to the 15-character story-text budget.", "", "| ID | Japanese | English |", "|---|---|---|"]
    for row in review:
        jp = row["japanese"].replace("<0A>", "<br>").replace("|", "\\|")
        en = row["english"].replace("\n", "<br>").replace("|", "\\|")
        lines.append(f"| `{row['id']}` | {jp} | {en} |")
    (ROOT / "translations/review_batch42.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"batch": 42, "translated_slots": len(blocks)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
