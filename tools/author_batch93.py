def main() -> None:
    destination = ROOT / "translations/batch93.json"
    if destination.exists():
        raise FileExistsError(destination)
    records = collect_messages(Rom(rom_paths()["blue"]))
    existing = translate_records(records)
    blocks = []
    for index, english in DIALOGUE.items():
        key = f"MSG/MESPAK02.PAK:017:{index:05d}"
        if key not in records or key in existing:
            raise ValueError(f"Missing or already translated source: {key}")
        row = records[key]
        if category(row) != "Story and dialogue":
            raise ValueError(f"Unexpected translation category for {key}")
        sources = ["Original Japanese ROM"]
        if index in {134, 135, 136, 149, 150, 160, 161, 189, 190, 191}:
            sources.append("https://digimon.net/reference_en/detail.php?directory_name=chibickmon")
        blocks.append({
            "archive": row["archive"], "entry": row["entry"],
            "start": row["index"], "category": "Story and dialogue",
            "english": [english], "sources": sources,
            "review_note": "Battle help and Sky Fort NPC dialogue. Battle mechanics and feature names follow the source text and established glossary; DigiXross is retained per the user's naming preference.",
        })
    if len(blocks) != 171:
        raise ValueError(f"Expected 171 dialogue strings, got {len(blocks)}")
    destination.write_text(json.dumps({
        "description": "Translate battle help, Sky Fort functions, and NPC dialogue in MESPAK02 entry 17.",
        "blocks": blocks,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"output": str(destination), "slots": len(blocks)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
